import 'dart:async';
import 'package:flutter/material.dart';
import '../../../../core/errors/failures.dart';
import '../../domain/entities/job_posting.dart';
import '../../domain/repositories/job_repository.dart';

class CompanyJobsProvider extends ChangeNotifier {
  final JobRepository _jobRepository;
  StreamSubscription<List<JobPosting>>? _jobsSubscription;

  List<JobPosting> _allJobs = [];
  JobStatus? _statusFilter;
  bool _isLoading = false;
  bool _isSaving = false;
  String? _errorMessage;
  String? _successMessage;

  CompanyJobsProvider({required JobRepository jobRepository})
      : _jobRepository = jobRepository;

  List<JobPosting> get jobs {
    if (_statusFilter == null) return _allJobs;
    return _allJobs.where((j) => j.status == _statusFilter).toList();
  }

  List<JobPosting> get allJobs => _allJobs;
  JobStatus? get statusFilter => _statusFilter;
  bool get isLoading => _isLoading;
  bool get isSaving => _isSaving;
  String? get errorMessage => _errorMessage;
  String? get successMessage => _successMessage;

  int get totalJobsCount => _allJobs.length;
  int get publishedJobsCount =>
      _allJobs.where((j) => j.status == JobStatus.published).length;
  int get draftJobsCount =>
      _allJobs.where((j) => j.status == JobStatus.draft).length;
  int get closedJobsCount =>
      _allJobs.where((j) => j.status == JobStatus.closed).length;
  int get totalApplicantsCount =>
      _allJobs.fold(0, (sum, j) => sum + j.applicantsCount);

  void clearMessages() {
    _errorMessage = null;
    _successMessage = null;
    notifyListeners();
  }

  void setStatusFilter(JobStatus? filter) {
    _statusFilter = filter;
    notifyListeners();
  }

  void listenCompanyJobs(String companyId) {
    _jobsSubscription?.cancel();
    _isLoading = true;
    notifyListeners();

    _jobsSubscription = _jobRepository.listenCompanyJobs(companyId).listen(
      (jobList) {
        _allJobs = jobList;
        _isLoading = false;
        notifyListeners();
      },
      onError: (e) {
        _errorMessage = e.toString();
        _isLoading = false;
        notifyListeners();
      },
    );
  }

  Future<void> loadCompanyJobs(String companyId) async {
    _isLoading = true;
    _errorMessage = null;
    notifyListeners();

    try {
      _allJobs = await _jobRepository.getCompanyJobs(companyId);
    } on Failure catch (e) {
      _errorMessage = e.message;
    } catch (e) {
      _errorMessage = e.toString();
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  Future<String?> createJob({
    required String companyId,
    required String companyName,
    String? companyLogoUrl,
    required String title,
    required String description,
    required JobType jobType,
    required WorkplaceType workplaceType,
    required ExperienceLevel experienceLevel,
    required JobLocation location,
    JobSalaryRange? salaryRange,
    List<String> requiredSkills = const [],
    List<String> optionalSkills = const [],
    List<String> requirements = const [],
    List<String> responsibilities = const [],
    List<String> benefits = const [],
    required JobStatus status,
    DateTime? deadline,
    String? examId,
  }) async {
    _isSaving = true;
    _errorMessage = null;
    notifyListeners();

    try {
      final newJob = JobPosting(
        id: '', // Generated by Firestore
        companyId: companyId,
        companyName: companyName,
        companyLogoUrl: companyLogoUrl,
        title: title.trim(),
        description: description.trim(),
        jobType: jobType,
        workplaceType: workplaceType,
        experienceLevel: experienceLevel,
        location: location,
        salaryRange: salaryRange,
        requiredSkills: requiredSkills,
        optionalSkills: optionalSkills,
        requirements: requirements,
        responsibilities: responsibilities,
        benefits: benefits,
        status: status,
        deadline: deadline,
        examId: examId,
        createdAt: DateTime.now(),
        updatedAt: DateTime.now(),
      );

      final newId = await _jobRepository.createJob(newJob);
      _successMessage = status == JobStatus.published
          ? 'Job vacancy successfully published!'
          : 'Job saved as draft.';
      return newId;
    } on Failure catch (e) {
      _errorMessage = e.message;
      return null;
    } catch (e) {
      _errorMessage = e.toString();
      return null;
    } finally {
      _isSaving = false;
      notifyListeners();
    }
  }

  Future<bool> updateJob(JobPosting job) async {
    _isSaving = true;
    _errorMessage = null;
    notifyListeners();

    try {
      await _jobRepository.updateJob(job);
      _successMessage = 'Job details updated.';
      return true;
    } on Failure catch (e) {
      _errorMessage = e.message;
      return false;
    } catch (e) {
      _errorMessage = e.toString();
      return false;
    } finally {
      _isSaving = false;
      notifyListeners();
    }
  }

  Future<bool> changeStatus(String jobId, JobStatus status) async {
    _isSaving = true;
    _errorMessage = null;
    notifyListeners();

    try {
      await _jobRepository.updateJobStatus(jobId, status);
      _successMessage = 'Job status changed to ${status.displayName}.';
      return true;
    } on Failure catch (e) {
      _errorMessage = e.message;
      return false;
    } catch (e) {
      _errorMessage = e.toString();
      return false;
    } finally {
      _isSaving = false;
      notifyListeners();
    }
  }

  Future<bool> deleteJob(String jobId) async {
    _isSaving = true;
    _errorMessage = null;
    notifyListeners();

    try {
      await _jobRepository.deleteJob(jobId);
      _allJobs.removeWhere((j) => j.id == jobId);
      _successMessage = 'Job vacancy deleted.';
      return true;
    } on Failure catch (e) {
      _errorMessage = e.message;
      return false;
    } catch (e) {
      _errorMessage = e.toString();
      return false;
    } finally {
      _isSaving = false;
      notifyListeners();
    }
  }

  @override
  void dispose() {
    _jobsSubscription?.cancel();
    super.dispose();
  }
}
